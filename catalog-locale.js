export function setupInterfaceTranslation(extra){
  const originals=new WeakMap();let running=false;
  function translateNode(node){
    if(node.nodeType!==3||node.parentElement?.closest('script,style,textarea,input,[data-no-translate]'))return;
    if(node.parentElement?.tagName==='OPTION'&&!node.parentElement.hasAttribute('value'))node.parentElement.value=node.parentElement.textContent;
    let record=originals.get(node);if(!record||node.data!==record.last)record={source:node.data,last:node.data};
    const next=document.documentElement.lang==='kk'?translateInterface(record.source,extra):record.source;
    if(node.data!==next)node.data=next;record.last=next;originals.set(node,record);
  }
  function walk(root){
    if(root.nodeType===3){translateNode(root);return;}
    if(root.nodeType!==1)return;
    const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);let text;while(text=walker.nextNode())translateNode(text);
    for(const element of [root,...root.querySelectorAll('[placeholder],[aria-label],[title]')])for(const attribute of ['placeholder','aria-label','title']){
      if(!element.hasAttribute(attribute))continue;
      // Preserve source attributes independently of editable values.
      const key='data-i18n-'+attribute,current=element.getAttribute(attribute);let source=element.getAttribute(key);
      if(!source||current!==source&&current!==translateInterface(source,extra)){source=current;element.setAttribute(key,source);}
      const next=document.documentElement.lang==='kk'?translateInterface(source,extra):source;if(current!==next)element.setAttribute(attribute,next);
    }
  }
  const observer=new MutationObserver(records=>{
    if(running)return;running=true;
    if(records.some(r=>r.target===document.documentElement&&r.attributeName==='lang'))walk(document.body);
    else for(const record of records){if(record.type==='characterData')translateNode(record.target);else for(const node of record.addedNodes)walk(node);}
    running=false;
  });
  observer.observe(document.body,{childList:true,subtree:true,characterData:true});
  observer.observe(document.documentElement,{attributes:true,attributeFilter:['lang']});walk(document.body);
}
